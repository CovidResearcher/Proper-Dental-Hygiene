def brush_teeth_routine():
    # Tools
    toothbrush_teeth = "regular toothbrush (for teeth)"
    toothbrush_tongue = "regular toothbrush (for tongue)"
    electric_toothbrush = "electric toothbrush (for toothpaste)"
    mouthwash = "mouthwash"
    toothpaste = "toothpaste"
    floss = "dental floss"

    print("=== Tooth Brushing Routine ===\n")

    # Step 1
    print("1. Rinse with mouthwash and scrub plaque off teeth")
    print(f"   - Use {toothbrush_teeth} + {mouthwash}")
    print("   - Scrub plaque from teeth utilizing the mouthwash\n")

    # Step 2
    print("2. Gargle and clean tongue")
    print("   - Gargle for 30+ seconds (several gargles)")
    print(f"   - Brush tongue with {toothbrush_tongue}\n")

    # Step 3
    print("3. Floss teeth")
    print(f"   - Use {floss}\n")

    # Step 4
    print("4. Repeat steps 1 & 2")
    print("   - Rinse with mouthwash + scrub teeth again")
    print("   - Gargle 30+ seconds + brush tongue again\n")

    # Step 5
    print("5. Final brush with toothpaste")
    print(f"   - Use {electric_toothbrush} + {toothpaste}")
    print("   - Brush teeth thoroughly")

# Run the routine
brush_teeth_routine()
